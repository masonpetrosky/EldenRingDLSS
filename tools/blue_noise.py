"""Generates the blue-noise tiles for rt_raygen.hlsl: src/blue_noise.hlsli with two 64x64 tiles of 8-bit ranks.

Void and cluster (Ulichney 1993): a Gaussian-filtered (sigma 1.5, toroidal) energy map; phase 1 ranks the ones of
a relaxed initial pattern by removing the tightest cluster, phase 2 adds ones at the largest void up to half the
texels, phase 3 fills the rest at the largest void. Deterministic (fixed seeds), so the header is reproducible.

usage: python tools/blue_noise.py   (writes src/blue_noise.hlsli)
"""
import os

import numpy as np

SIZE = 64
SIGMA = 1.5
TILES = 2


def kernel():
    d = np.minimum(np.arange(SIZE), SIZE - np.arange(SIZE)).astype(np.float64)
    return np.exp(-(d[:, None] ** 2 + d[None, :] ** 2) / (2 * SIGMA * SIGMA))


def energy_of(pattern, k):
    return np.real(np.fft.ifft2(np.fft.fft2(pattern) * np.fft.fft2(k)))


def tile(seed):
    rng = np.random.default_rng(seed)
    k = kernel()
    n = SIZE * SIZE
    pattern = np.zeros((SIZE, SIZE), dtype=bool)
    pattern.flat[rng.choice(n, n // 10, replace=False)] = True

    # Relax the initial pattern: move the tightest cluster to the largest void until they coincide.
    energy = energy_of(pattern, k)
    while True:
        cluster = np.unravel_index(np.argmax(np.where(pattern, energy, -np.inf)), pattern.shape)
        pattern[cluster] = False
        energy -= np.roll(k, cluster, axis=(0, 1))
        void = np.unravel_index(np.argmin(np.where(pattern, np.inf, energy)), pattern.shape)
        if void == cluster:
            pattern[cluster] = True
            energy += np.roll(k, cluster, axis=(0, 1))
            break
        pattern[void] = True
        energy += np.roll(k, void, axis=(0, 1))

    ranks = np.zeros((SIZE, SIZE), dtype=np.int64)
    ones = int(pattern.sum())

    # Phase 1: rank the initial ones, tightest cluster first, from ones - 1 down to 0.
    p = pattern.copy()
    e = energy.copy()
    for rank in range(ones - 1, -1, -1):
        cluster = np.unravel_index(np.argmax(np.where(p, e, -np.inf)), p.shape)
        p[cluster] = False
        e -= np.roll(k, cluster, axis=(0, 1))
        ranks[cluster] = rank

    # Phases 2 and 3: from the initial pattern, add a one at the largest void until every texel is ranked.
    p = pattern.copy()
    e = energy.copy()
    for rank in range(ones, n):
        void = np.unravel_index(np.argmin(np.where(p, np.inf, e)), p.shape)
        p[void] = True
        e += np.roll(k, void, axis=(0, 1))
        ranks[void] = rank

    return (ranks * 256 // n).astype(np.uint8)  # 64 texels per 8-bit value


def main():
    root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
    data = np.concatenate([tile(1000 + i).ravel() for i in range(TILES)])
    words = data.view("<u4")
    lines = ["// Generated by tools/blue_noise.py: %d blue-noise tiles of %dx%d, 8-bit ranks (void and cluster, sigma %.1f)," %
             (TILES, SIZE, SIZE, SIGMA),
             "// four texels per uint, row-major, little-endian. Do not edit; rerun the script.",
             "static const uint kBlueNoiseSize = %d;" % SIZE,
             "static const uint kBlueNoise[%d] = {" % len(words)]
    for i in range(0, len(words), 8):
        lines.append("  " + ", ".join("0x%08Xu" % w for w in words[i:i + 8]) + ",")
    lines.append("};")
    with open(os.path.join(root, "src", "blue_noise.hlsli"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    # Quick check: the spectrum's low-frequency energy should be far below white noise's.
    t = data[:SIZE * SIZE].reshape(SIZE, SIZE).astype(np.float64)
    spectrum = np.abs(np.fft.fft2(t - t.mean())) ** 2
    f = np.hypot(*np.meshgrid(np.fft.fftfreq(SIZE), np.fft.fftfreq(SIZE)))
    low = spectrum[(f > 0) & (f < 0.1)].mean() / spectrum[f > 0].mean()
    print("wrote src/blue_noise.hlsli; low-frequency energy vs average: %.3f (white noise: about 1)" % low)


if __name__ == "__main__":
    main()
